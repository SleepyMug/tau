#!/usr/bin/env node
// Generates tau's code from its protos (proto/, buf.yaml and buf.gen.yaml):
// `buf generate`, into src/gen; and src/gen/descriptors.ts, the schema as a
// FileDescriptorSet with its comments and every file it imports, as
// `buf build` makes it, for a backend that registers it where its comments
// are read, such as a gateway that makes clients of it.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const buf = (...args) => execFileSync("buf", args, { stdio: ["ignore", "inherit", "inherit"] });

rmSync("src/gen", { recursive: true, force: true });
buf("lint");
buf("generate");
const dir = mkdtempSync(join(tmpdir(), "tau-gen-"));
try {
	buf("build", "--output", join(dir, "descriptors.binpb"));
	const encoded = readFileSync(join(dir, "descriptors.binpb")).toString("base64");
	writeFileSync(
		"src/gen/descriptors.ts",
		[
			"// @generated by scripts/gen.mjs from proto/, with `buf build`: do not edit.",
			"",
			'import { fromBinary } from "@bufbuild/protobuf";',
			'import { type FileDescriptorSet, FileDescriptorSetSchema } from "@bufbuild/protobuf/wkt";',
			"",
			"/** tau's schema, with its comments and every file it imports. */",
			"export function descriptors(): FileDescriptorSet {",
			`\treturn fromBinary(FileDescriptorSetSchema, Buffer.from(${JSON.stringify(encoded)}, "base64"));`,
			"}",
			"",
		].join("\n"),
	);
} finally {
	rmSync(dir, { recursive: true, force: true });
}
